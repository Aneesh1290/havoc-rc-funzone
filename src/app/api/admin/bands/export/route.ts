import { NextRequest, NextResponse } from "next/server";
import { checkSessionAction } from "@/app/login/actions";
import { getBandItems, getBandInventorySummary, getBandTransactions } from "@/lib/band-inventory-db";

function escapeCsvField(val: any): string {
  if (val === null || val === undefined) return '""';
  const str = String(val).replace(/"/g, '""');
  return `"${str}"`;
}

export async function GET(req: NextRequest) {
  try {
    const session = await checkSessionAction();
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const { searchParams } = new URL(req.url);
    const reportType = searchParams.get("type") || "master"; // 'master' | 'summary' | 'movements'
    const nowStr = new Date().toISOString().split("T")[0];

    if (reportType === "summary") {
      const summary = await getBandInventorySummary();
      const lines: string[] = [];

      lines.push("RC FUNZONE - WRISTBAND INVENTORY STOCK SUMMARY REPORT");
      lines.push(`Generated On:,"${new Date().toLocaleString()}"`);
      lines.push(`Generated By:,"${session.username || "Admin"}"`);
      lines.push("");

      lines.push("OVERALL KEY PERFORMANCE METRICS");
      lines.push("Metric,Count");
      lines.push(`Total Master Bands,${summary.totalBands}`);
      lines.push(`Available In Stock,${summary.available}`);
      lines.push(`Currently Issued (On Track),${summary.issued}`);
      lines.push(`Damaged / Quarantine,${summary.damaged}`);
      lines.push(`Reported Lost,${summary.lost}`);
      lines.push(`Retired / Written-off,${summary.retired}`);
      lines.push(`Active Inventory Pool,${summary.activeInventory}`);
      lines.push(`Availability Rate,${summary.availabilityRate}%`);
      lines.push(`Issued Today,${summary.issuedToday}`);
      lines.push(`Returned Today,${summary.returnedToday}`);
      lines.push("");

      lines.push("COLOR-WISE STOCK BREAKDOWN");
      lines.push("Color Name,Color Hex,Total Bands,Available,Issued,Damaged,Lost,Retired,Availability %");
      for (const c of summary.colorBreakdown) {
        const rate = c.total > 0 ? Math.round((c.available / c.total) * 100) : 0;
        lines.push([
          escapeCsvField(c.color_name),
          escapeCsvField(c.color_hex),
          c.total,
          c.available,
          c.issued,
          c.damaged,
          c.lost,
          c.retired,
          `${rate}%`,
        ].join(","));
      }

      const csvContent = lines.join("\r\n");
      return new NextResponse(csvContent, {
        status: 200,
        headers: {
          "Content-Type": "text/csv; charset=utf-8",
          "Content-Disposition": `attachment; filename="Havoc_Band_Stock_Summary_${nowStr}.csv"`,
        },
      });
    }

    if (reportType === "movements") {
      const { transactions } = await getBandTransactions({ limit: 1000 });
      const lines: string[] = [];

      lines.push("Date & Time,Band Code,Color,Movement Type,Customer Name,Order / Booking ID,Staff Member,Remarks / Notes");
      for (const t of transactions) {
        lines.push([
          escapeCsvField(t.created_at),
          escapeCsvField(t.band_code),
          escapeCsvField(t.color_name),
          escapeCsvField(t.transaction_type),
          escapeCsvField(t.customer_name || "-"),
          escapeCsvField(t.order_number || (t.booking_id ? `#${t.booking_id}` : "-")),
          escapeCsvField(t.staff_name || "-"),
          escapeCsvField(t.notes || "-"),
        ].join(","));
      }

      const csvContent = lines.join("\r\n");
      return new NextResponse(csvContent, {
        status: 200,
        headers: {
          "Content-Type": "text/csv; charset=utf-8",
          "Content-Disposition": `attachment; filename="Havoc_Band_Movements_Log_${nowStr}.csv"`,
        },
      });
    }

    // Default: 'master' list
    const { items } = await getBandItems({});
    const lines: string[] = [];

    lines.push("Band ID,Color Name,Color Hex,Category,Current Status,Current Holder,Order #,Total Uses,Notes,Last Updated,Created At");
    for (const b of items) {
      lines.push([
        escapeCsvField(b.band_code),
        escapeCsvField(b.color_name),
        escapeCsvField(b.color_hex),
        escapeCsvField(b.category),
        escapeCsvField(b.status.toUpperCase()),
        escapeCsvField(b.current_holder_name || "-"),
        escapeCsvField(b.current_order_number || "-"),
        b.total_uses,
        escapeCsvField(b.notes || "-"),
        escapeCsvField(b.updated_at),
        escapeCsvField(b.created_at),
      ].join(","));
    }

    const csvContent = lines.join("\r\n");
    return new NextResponse(csvContent, {
      status: 200,
      headers: {
        "Content-Type": "text/csv; charset=utf-8",
        "Content-Disposition": `attachment; filename="Havoc_Band_Master_Inventory_${nowStr}.csv"`,
      },
    });
  } catch (err: any) {
    console.error("[Band Export Error]", err);
    return NextResponse.json({ error: "Failed to export report" }, { status: 500 });
  }
}
